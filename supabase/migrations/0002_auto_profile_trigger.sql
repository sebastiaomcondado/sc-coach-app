-- Auto-creates a profiles row whenever a new auth user is created, using
-- metadata passed at signup time. Runs as SECURITY DEFINER so it bypasses
-- RLS — this is what lets it work even before a user confirms their email
-- (i.e. before they have an active session of their own).

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'role', 'athlete')
  );
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();
